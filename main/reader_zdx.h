// reader_zdx.h — chunked, randomly-readable compressed books.
//
// A .zdx file stores the original UTF-8 text split into fixed-size chunks,
// each independently raw-deflate compressed. reader_zdx_read() exposes the
// ORIGINAL byte offsets, so bookmarks, progress, chapter offsets and the
// paginator keep working unchanged: they never see the compressed layout.
//
// Layout (all integers little-endian):
//   0..3    magic "ZDX1"
//   4       version (1)
//   5       flags (bit0 = raw deflate; other bits reserved)
//   6..7    reserved (0)
//   8..11   chunk size in original bytes (16384 for new files)
//   12..15  chunk count
//   16..19  original byte length (uncompressed UTF-8)
//   20..23  non-whitespace code points (hint, generated by encoder)
//   24..31  reserved (0)
//   32..    chunk table: chunk_count entries of { u32 data_offset, u32 length }
//   ...     compressed chunk data, concatenated
//
// Chunk size is a ratio/RAM trade-off, not a format constant. A chunk is one
// independent deflate stream, so its LZ77 window can never see the previous
// chunk; 4 KiB chunks (the original choice) therefore threw away most of the
// redundancy of Chinese UTF-8 text. Measured on assets/books/ginga.txt, one
// independent stream per N bytes compresses to:
//
//     N = 4 KiB -> 55.3 %   N = 16 KiB -> 51.2 %   N = 32 KiB -> 50.6 %
//
// 16 KiB captures nearly all of the gain for a 16 KiB dictionary buffer, and it
// is what the encoder emits now. Larger sizes are rejected by the header check
// below; smaller ones still load, so books uploaded by an earlier firmware keep
// working and are simply re-compressed on the next upload.
//
// The device has no PSRAM, so the decoder keeps bounded buffers: a dictionary
// ring of the chunk size, a small output hold-back window and a small
// compressed-input window that is refilled from the file while inflating. A
// random read inside a chunk re-inflates from that chunk's start, which is
// ~8 KiB of typical work per page turn, not a whole-file decode.
#pragma once

#include <stddef.h>
#include <stdint.h>
#include <stdio.h>

#include "uzlib.h"

#define READER_ZDX_MAGIC       "ZDX1"
#define READER_ZDX_VERSION     1u
// Largest accepted chunk (== deflate window) in original bytes. Books written
// by this firmware use READER_ZDX_ENCODE_CHUNK; the cap only bounds RAM.
#define READER_ZDX_CHUNK       16384u
// Chunk size the encoder (transfer page, tools/zdx_codec.py) must emit.
#define READER_ZDX_ENCODE_CHUNK READER_ZDX_CHUNK
#define READER_ZDX_HEADER_SIZE 32u
#define READER_ZDX_TABLE_ENTRY 8u
// Compressed input is streamed, so this only bounds one refill.
#define READER_ZDX_COMP_CAP    2048u
// Decoded bytes kept resident. A page read is ~1 KiB, so one window serves
// several sequential reads before the chunk has to be re-inflated.
#define READER_ZDX_OUT_CAP     4096u

typedef struct {
    FILE *fp;                      // file source (uploaded books), or NULL
    const unsigned char *mem;      // memory source (built-in books), or NULL
    size_t mem_len;
    size_t mem_pos;

    uint32_t chunk_count;
    uint32_t chunk_size;
    uint32_t original_size;
    uint32_t text_chars;
    uint32_t data_start;
    long file_size;

    // Hold-back window: out[0..cache_len) are original bytes of chunk
    // `cache_index`, starting at intra-chunk offset cache_start.
    uint32_t cache_index;          // UINT32_MAX when the window is empty
    uint32_t cache_start;
    uint32_t cache_len;

    // Inflate state of the chunk currently set up in `infl`.
    uint32_t dec_index;            // UINT32_MAX when nothing is set up
    uint32_t dec_produced;         // original bytes produced for dec_index
    uint32_t comp_off;             // compressed stream offset in the file
    uint32_t comp_len;
    uint32_t comp_pos;
    int dec_done;                  // the chunk's deflate stream ended

    TINF_DATA infl;
    unsigned char dict[READER_ZDX_CHUNK];
    unsigned char out[READER_ZDX_OUT_CAP];
    unsigned char comp[READER_ZDX_COMP_CAP];
} reader_zdx_t;

// Validate the header and prepare the reader. Returns 0 on success, -1 when
// the file is not a supported zdx (bad magic, version, sizes or truncated
// table). The FILE is closed on failure only.
int reader_zdx_open(reader_zdx_t *z, FILE *fp);

// Same, but for a zdx image held in flash/RAM (built-in books). `data` must
// remain valid for the lifetime of the reader. No copies are made.
int reader_zdx_open_mem(reader_zdx_t *z, const unsigned char *data, size_t len);

// Read up to len ORIGINAL bytes starting at ORIGINAL offset. Returns bytes
// copied (0 at EOF or on a corrupt chunk); may span several chunks.
size_t reader_zdx_read(reader_zdx_t *z, size_t offset, char *buf, size_t len);

// True when the whole stream inflated without CRC/structure errors. Used by
// the upload gate to reject truncated or damaged files before they reach the
// shelf. O(n) over all chunks but runs only once, on the HTTP worker.
int reader_zdx_verify(reader_zdx_t *z);

void reader_zdx_close(reader_zdx_t *z);

// Lightweight header probe for the shelf listing: reads only the 32-byte
// header, needs no decoder buffers. Returns 0 and fills the two size fields
// when `fp` holds a supported zdx, -1 otherwise. FILE is rewound.
int reader_zdx_probe(FILE *fp, uint32_t *original_size, uint32_t *text_chars);

uint32_t reader_zdx_original_size(const reader_zdx_t *z);
uint32_t reader_zdx_text_chars(const reader_zdx_t *z);