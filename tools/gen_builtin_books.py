#!/usr/bin/env python3
"""Generate compressed built-in book data from assets/books/*.txt.

The two built-in books used to be plain UTF-8 C strings costing ~84 KiB of
flash. Their canonical text now lives in assets/books/*.txt (also scanned by
the font generator); this tool compresses each into a zdx image and emits
main/builtin_books_data.{c,h}. On the device reader_store_read() decodes the
built-in zdx just like an uploaded book, so logical byte offsets, bookmarks and
progress are unchanged.

  python3 tools/gen_builtin_books.py          # regenerate (edit the .txt first)
  python3 tools/gen_builtin_books.py --check  # verify committed data is current

The generated files are committed; normal builds never need to run this tool.

`--check` is semantic, not byte-identical: raw-deflate output depends on the
zlib build (zlib-ng and zlib 1.3 disagree by a few bytes on the same input), so
it decodes the committed images and compares them with the canonical text
instead of re-compressing. Regenerating on a different zlib build may change
bytes without changing content; that diff is not worth committing.
"""
from __future__ import annotations

import re
import sys
import zlib
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "tools"))
import zdx_codec  # noqa: E402

BOOKS_DIR = ROOT / "assets" / "books"
OUT_C = ROOT / "main" / "builtin_books_data.c"
OUT_H = ROOT / "main" / "builtin_books_data.h"

# Output stems in table order. Index 0 = guide, 1 = novel.
ENTRIES = ["guide", "ginga"]


def extract_text(stem: str) -> bytes:
    # assets/books/*.txt is the canonical text and the single source of truth.
    path = BOOKS_DIR / f"{stem}.txt"
    if not path.is_file():
        raise RuntimeError(f"missing canonical book text: {path}")
    return path.read_bytes()


def c_array(name: str, data: bytes) -> str:
    lines = []
    for i in range(0, len(data), 16):
        row = data[i:i + 16]
        lines.append("    " + ",".join(f"0x{b:02X}" for b in row) + ",")
    return (f"const unsigned char {name}[{len(data)}] = {{\n"
            + "\n".join(lines) + "\n};\n")


def render() -> tuple[str, str, list[tuple[str, int, int, int]]]:
    """Build the generated file contents and per-book metadata."""
    blobs: list[bytes] = []
    meta: list[tuple[str, int, int, int]] = []
    for stem in ENTRIES:
        raw = extract_text(stem)
        blob = zdx_codec.encode(raw)
        blobs.append(blob)
        f = zdx_codec.header_fields(blob)
        meta.append((stem, len(raw), len(blob), f["text_chars"]))

    # Header: extern declarations for each book's zdx image.
    h = [
        "// Generated by tools/gen_builtin_books.py -- do not edit by hand.",
        "// Compressed built-in book images (zdx format), decoded on device by",
        "// reader_zdx_open_mem(). The canonical UTF-8 text lives in assets/books/.",
        "#pragma once",
        "",
        "#include <stddef.h>",
        "",
    ]
    for stem, blob in zip(ENTRIES, blobs):
        f = zdx_codec.header_fields(blob)
        h.append(f"extern const unsigned char g_builtin_zdx_{stem}[{len(blob)}];")
        h.append(f"#define READER_ZDX_{stem.upper()}_ORIG_SIZE {f['original_size']}u")
        h.append(f"#define READER_ZDX_{stem.upper()}_TEXT_CHARS {f['text_chars']}u")
    h.append("")
    h.append("typedef struct {")
    h.append("    const unsigned char *zdx;")
    h.append("    size_t zdx_len;")
    h.append("} reader_builtin_zdx_t;")
    h.append("")
    h.append(f"#define READER_BUILTIN_ZDX_COUNT {len(ENTRIES)}")
    h.append("extern const reader_builtin_zdx_t g_builtin_zdx[];")
    h.append("")

    c = [
        "// Generated by tools/gen_builtin_books.py -- do not edit by hand.",
        '#include "builtin_books_data.h"',
        "",
    ]
    for stem, blob in zip(ENTRIES, blobs):
        c.append(c_array(f"g_builtin_zdx_{stem}", blob))
    c.append("")
    c.append("const reader_builtin_zdx_t g_builtin_zdx[] = {")
    for stem in ENTRIES:
        c.append(f"    {{ g_builtin_zdx_{stem}, sizeof(g_builtin_zdx_{stem}) }},")
    c.append("};")
    c.append("")
    return "\n".join(h), "\n".join(c), meta


ARRAY_RE = re.compile(
    r"const unsigned char (g_builtin_zdx_\w+)\[(\d+)\] = \{(.*?)\n\};", re.S)


def committed_images() -> dict[str, bytes]:
    images: dict[str, bytes] = {}
    text = OUT_C.read_text(encoding="utf-8")
    for name, declared, body in ARRAY_RE.findall(text):
        data = bytes(int(byte, 16) for byte in re.findall(r"0x([0-9A-Fa-f]{2})", body))
        if len(data) != int(declared):
            raise ValueError(
                f"{OUT_C.name}: {name} declares {declared} bytes but holds {len(data)}")
        images[name] = data
    return images


def check() -> bool:
    """Decode the committed images and compare them with the canonical text."""
    if not OUT_C.is_file() or not OUT_H.is_file():
        print("ERROR: generated book data is missing; "
              "run python3 tools/gen_builtin_books.py", file=sys.stderr)
        return False
    try:
        images = committed_images()
    except ValueError as error:
        print(f"ERROR: {error}; run python3 tools/gen_builtin_books.py",
              file=sys.stderr)
        return False

    header = OUT_H.read_text(encoding="utf-8")
    errors: list[str] = []
    for stem in ENTRIES:
        name = f"g_builtin_zdx_{stem}"
        blob = images.get(name)
        if blob is None:
            errors.append(f"{OUT_C.name}: missing {name}")
            continue
        try:
            fields = zdx_codec.header_fields(blob)
            decoded = zdx_codec.decode(blob)
        except (ValueError, AssertionError, zlib.error) as error:
            errors.append(f"{OUT_C.name}: {name} is not a valid zdx image: {error}")
            continue
        if decoded != extract_text(stem):
            errors.append(f"{OUT_C.name}: {name} does not decode to "
                          f"assets/books/{stem}.txt")
        for expected in (
            f"extern const unsigned char {name}[{len(blob)}];",
            f"#define READER_ZDX_{stem.upper()}_ORIG_SIZE {fields['original_size']}u",
            f"#define READER_ZDX_{stem.upper()}_TEXT_CHARS {fields['text_chars']}u",
        ):
            if expected not in header:
                errors.append(f"{OUT_H.name}: missing or stale: {expected}")

    for error in errors:
        print(f"ERROR: {error}; run python3 tools/gen_builtin_books.py",
              file=sys.stderr)
    if errors:
        return False
    print("Builtin book data: PASS (committed images match assets/books/*.txt)")
    return True


def main() -> int:
    if "--check" in sys.argv[1:]:
        return 0 if check() else 1

    h, c, meta = render()
    for stem, raw_len, zdx_len, chars in meta:
        print(f"{stem}: {raw_len} B UTF-8 -> {zdx_len} B zdx "
              f"({100 * zdx_len // raw_len}%), chars={chars}")

    OUT_H.write_text(h, encoding="utf-8")
    OUT_C.write_text(c, encoding="utf-8")
    print(f"wrote {OUT_C.relative_to(ROOT)}, {OUT_H.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
