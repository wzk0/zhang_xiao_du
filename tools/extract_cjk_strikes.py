#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Regenerate assets/fonts/cjk_strikes.txt from WenQuanYi bitmap-song BDFs.

The committed table is enough to build the fonts; this script is only needed
when the character inventory changes or the strikes are refreshed.

How to obtain the BDF sources (Debian/Ubuntu)::

    sudo apt-get install xfonts-wqy pcf2bdf
    mkdir -p /tmp/wqy-bdf
    for f in wenquanyi_10pt wenquanyi_13px wenquanyi_11pt wenquanyi_12pt; do
        pcf2bdf /usr/share/fonts/X11/misc/$f.pcf > /tmp/wqy-bdf/$f.bdf
    done
    python3 tools/extract_cjk_strikes.py --bdf-dir /tmp/wqy-bdf

WenQuanYi bitmap-song is GPL-2-with-font-embedding-exception; see
assets/fonts/LICENSE.wqy-bitmapfont.txt. Only the extracted dot-matrix table
is shipped, not the PCF/BDF files themselves.
"""
from __future__ import annotations

import argparse
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
FONT_DIR = ROOT / "assets" / "fonts"
CHARSET_FILE = FONT_DIR / "charset.txt"
OUT = FONT_DIR / "cjk_strikes.txt"

# selectable font size -> (bdf file, strike size)
STRIKES = [
    (12, "wenquanyi_10pt.bdf", "wenquanyi_10pt.pcf"),
    (13, "wenquanyi_13px.bdf", "wenquanyi_13px.pcf"),
    (14, "wenquanyi_11pt.bdf", "wenquanyi_11pt.pcf"),
    (16, "wenquanyi_12pt.bdf", "wenquanyi_12pt.pcf"),
]

LINE_RE = re.compile(r"(?m)^U\+([0-9A-Fa-f]{4,6})\s*$")


def parse_bdf(text: str) -> dict[int, tuple[int, int, int, int, int, list[list[int]]]]:
    """Return {codepoint: (w, h, xoff, yoff, dwidth, rows)} for a BDF file."""
    out = {}
    lines = text.splitlines()
    i, n = 0, len(lines)
    while i < n:
        if not lines[i].startswith("STARTCHAR"):
            i += 1
            continue
        enc = None
        bbx = None
        dw = None
        rows: list[list[int]] = []
        i += 1
        while i < n and not lines[i].startswith("ENDCHAR"):
            ln = lines[i].strip()
            if ln.startswith("ENCODING "):
                enc = int(ln.split()[1])
            elif ln.startswith("DWIDTH "):
                p = ln.split()
                dw = int(p[1])
            elif ln.startswith("BBX "):
                bbx = tuple(int(x) for x in ln.split()[1:5])
            elif ln == "BITMAP":
                i += 1
                while i < n and not lines[i].startswith("ENDCHAR"):
                    hexrow = lines[i].strip()
                    if hexrow:
                        bits = bin(int(hexrow, 16))[2:].zfill(len(hexrow) * 4)
                        rows.append([1 if c == "1" else 0 for c in bits])
                    i += 1
                continue
            i += 1
        if enc is not None and enc >= 0 and bbx:
            w, h, xo, yo = bbx
            rows = [r[:w] for r in rows[:h]]
            out[enc] = (w, h, xo, yo, dw or w, rows)
        i += 1
    return out


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--bdf-dir", default="/tmp/wqy-bdf",
                    help="directory holding the four converted BDF files")
    args = ap.parse_args()
    bdf_dir = Path(args.bdf_dir)

    cps = sorted({int(m, 16) for m in LINE_RE.findall(CHARSET_FILE.read_text(encoding="utf-8"))
                  if 0x4E00 <= int(m, 16) <= 0x9FFF})
    if not cps:
        raise SystemExit("no CJK code points in charset.txt")
    print(f"CJK code points in inventory: {len(cps)}")

    lines = [
        "# WenQuanYi bitmap-song native CJK strikes (generated by tools/extract_cjk_strikes.py).",
        "# Source: Debian xfonts-wqy (wqy-bitmapfont-bdf), PCF -> BDF via pcf2bdf.",
        "# License: GPL-2-with-font-embedding-exception; see LICENSE.wqy-bitmapfont.txt.",
        "# Each glyph is a size x size em-square bitmap, row-major, MSB-first.",
        "# BDF boxes are placed on the strike baseline (not stretched), so sparse",
        "# glyphs such as 一 keep their true vertical position.",
        "# Lines: U+XXXX <w> <h> <hex bits, w*h bits total>.",
        "",
    ]
    for size, bdf_name, src in STRIKES:
        path = bdf_dir / bdf_name
        if not path.is_file():
            raise SystemExit(f"missing {path}; see this script's docstring")
        d = parse_bdf(path.read_text(encoding="utf-8", errors="replace"))
        # Most Hanzi share one yoff; that fixes the baseline inside the em box.
        yoffs = [d[cp][3] for cp in cps if cp in d and d[cp][0] == d[cp][1] == size]
        yoff_ref = max(set(yoffs), key=yoffs.count) if yoffs else -1
        baseline_row = size - 1 + yoff_ref
        lines.append(f"==STRIKE size={size} source={src} baseline_row={baseline_row}")
        kept = missing = 0
        for cp in cps:
            g = d.get(cp)
            if g is None:
                missing += 1
                continue
            bw, bh, xo, yo, _dw, rows = g
            box = [[0] * size for _ in range(size)]
            for j in range(bh):
                y_up = yo + bh - 1 - j
                row = baseline_row - y_up
                for c in range(bw):
                    col = xo + c
                    if 0 <= row < size and 0 <= col < size and rows[j][c]:
                        box[row][col] = 1
            bits = "".join("1" if v else "0" for r in box for v in r)
            nibble = (len(bits) + 3) // 4
            # 13x13 = 169 bits is NOT a multiple of 4. Pad on the RIGHT before
            # converting to hex: gen_reader_font.load_strikes() zfills the hex
            # back to a multiple of 4 and drops the trailing padding. Padding
            # on the left instead would shift every row by 3 pixels.
            padded = bits.ljust(nibble * 4, "0")
            lines.append(f"U+{cp:04X} {size} {size} {int(padded, 2):0{nibble}X}")
            kept += 1
        print(f"  {size}px: {kept} glyphs, {missing} missing, baseline_row={baseline_row}")
        if missing:
            raise SystemExit(f"{size}px strike misses {missing} Hanzi; aborting")
        lines.append("")

    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)} ({OUT.stat().st_size} bytes)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
