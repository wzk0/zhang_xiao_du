#!/usr/bin/env python3
"""Extract one shared 16 px GB2312 level-2 strike from WenQuanYi Bitmap Song."""
from __future__ import annotations

import argparse
from pathlib import Path

from extract_cjk_strikes import FONT_DIR, parse_bdf

BASELINE = 13
SIZE = 16
OUT = FONT_DIR / "reader_fallback_data.h"


def level_two() -> list[int]:
    codepoints = []
    for first in range(0xD8, 0xF8):
        for second in range(0xA1, 0xFF):
            try:
                codepoints.append(ord(bytes((first, second)).decode("gb2312")))
            except UnicodeDecodeError:
                continue
    return sorted(codepoints)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("bdf", type=Path, help="wenquanyi_12pt.bdf from xfonts-wqy")
    args = parser.parse_args()
    bdf = parse_bdf(args.bdf.read_text(encoding="utf-8"))
    points = level_two()
    output = [
        "// Generated by tools/gen_reader_fallback.py from WenQuanYi Bitmap Song.",
        "// GPL-2 with font embedding exception. See LICENSE.wqy-bitmapfont.txt.",
        "#pragma once",
        "#include <stdint.h>",
        "",
        f"#define READER_FALLBACK_BASELINE {BASELINE}",
        "static const uint16_t fallback_codepoints[] = {",
    ]
    for i in range(0, len(points), 12):
        output.append("    " + "".join(f"0x{cp:04X}, " for cp in points[i:i + 12]).rstrip())
    output.extend(("};", "", f"static const uint16_t fallback_rows[][{SIZE}] = {{"))
    for cp in points:
        w, h, xoff, yoff, _advance, pixels = bdf[cp]
        rows = [0] * SIZE
        for j in range(h):
            y = BASELINE - (yoff + h - 1 - j)
            for c in range(w):
                x = xoff + c
                if pixels[j][c]:
                    if not (0 <= x < SIZE and 0 <= y < SIZE):
                        raise ValueError(f"U+{cp:04X} has ink outside its em box")
                    rows[y] |= 1 << x
        if not any(rows):
            raise ValueError(f"U+{cp:04X} has an empty glyph")
        output.append("    {" + ", ".join(f"0x{row:04X}" for row in rows) + f"}}, // U+{cp:04X}")
    OUT.write_text("\n".join(output + ["};", ""]), encoding="utf-8")


if __name__ == "__main__":
    main()
